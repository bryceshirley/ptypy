@unittest.skipIf(not HAVE_TORCH, "PyTorch is not installed")
class FirstBornCoreTest(unittest.TestCase):
    """first_born_step against an independent model and against autograd."""

    def _step(self, O, P, I_dat, H_fwd, H_rev, mask=None, probe=True):
        return first_born_step(O, P, I_dat, H_fwd, H_rev, _ff_fw, _ff_bw,
                               mask=mask, calc_probe_grad=probe)

    # -- the forward model ---------------------------------------------------
    def test_forward_matches_reference(self):
        """I_mod is the intensity of the psi written in the docstring."""
        O, P, I_dat, H_fwd, H_rev = _setup()
        _, _, _, _, r_field, I_mod = self._step(O, P, I_dat, H_fwd, H_rev)

        psi = _reference_psi(O, P, H_fwd, H_rev)
        F = _ff_fw(psi)
        expect = (F.real**2 + F.imag**2).sum(dim=1)
        np.testing.assert_allclose(I_mod.numpy(), expect.numpy(), rtol=1e-12,
                                   atol=1e-12)

    def test_single_slice_is_the_ordinary_model(self):
        """At N = 1 the model is exactly psi = O P, not an approximation."""
        O, P, I_dat, H_fwd, H_rev = _setup(N=1, weak=0.4)
        _, _, _, _, r_field, I_mod = self._step(O, P, I_dat, H_fwd, H_rev)

        F = _ff_fw(O[0].unsqueeze(1) * P.unsqueeze(0))
        expect = (F.real**2 + F.imag**2).sum(dim=1)
        np.testing.assert_allclose(I_mod.numpy(), expect.numpy(), rtol=1e-12,
                                   atol=1e-12)

    def test_unbatched_matches_batch_of_one(self):
        """A 3-dim O must give what the same O as a batch of one gives."""
        O, P, I_dat, H_fwd, H_rev = _setup(B=1)
        b = self._step(O, P, I_dat, H_fwd, H_rev)
        s = self._step(O[:, 0], P, I_dat[0], H_fwd, H_rev)

        np.testing.assert_allclose(s[0].numpy(), b[0][:, 0].numpy(), atol=1e-12)
        np.testing.assert_allclose(s[1].numpy(), b[1].numpy(), atol=1e-12)
        np.testing.assert_allclose(s[2].numpy(), b[2].numpy(), atol=1e-12)
        np.testing.assert_allclose(s[5].numpy(), b[5][0].numpy(), atol=1e-12)

    # -- the amplitude projection -------------------------------------------
    def test_r_field_is_the_projection_residual(self):
        """
        psi + r_field is the exit wave with the measured modulus: the far-field
        intensity of psi + r_field is I_dat wherever the mask is open, and is
        left at I_mod where it is closed.
        """
        O, P, I_dat, H_fwd, H_rev = _setup()
        mask = torch.ones_like(I_dat)
        mask[:, :4] = 0.0
        _, _, _, _, r_field, I_mod = self._step(O, P, I_dat, H_fwd, H_rev,
                                                mask=mask)

        psi = _reference_psi(O, P, H_fwd, H_rev)
        F = _ff_fw(psi + r_field)
        got = (F.real**2 + F.imag**2).sum(dim=1)

        open_ = mask > 0
        np.testing.assert_allclose(got[open_].numpy(), I_dat[open_].numpy(),
                                   rtol=1e-10)
        np.testing.assert_allclose(got[~open_].numpy(), I_mod[~open_].numpy(),
                                   rtol=1e-10)

    def test_masked_out_data_do_not_contribute(self):
        """A fully closed mask leaves every gradient at exactly zero."""
        O, P, I_dat, H_fwd, H_rev = _setup()
        mask = torch.zeros_like(I_dat)
        grad_g, _, grad_P, _, r_field, _ = self._step(O, P, I_dat, H_fwd, H_rev,
                                                      mask=mask)
        for name, t in (("grad_g", grad_g), ("grad_P", grad_P),
                        ("r_field", r_field)):
            self.assertEqual(float(t.abs().max()), 0.0, f"{name} is not zero")

    # -- the gradients -------------------------------------------------------
    #
    # psi is exactly affine in O and in P, and the returned gradients are the
    # adjoint of that map applied to the projection residual. So with the
    # projected wave held fixed at t = psi + r_field,
    #
    #     L(O, P) = 0.5 sum |psi(O, P) - t|^2
    #
    # has dL/dO* = -grad_g and dL/dP* = -grad_P exactly. torch.autograd returns
    # precisely the conjugate Wirtinger derivative, so this is a direct check
    # of both adjoints with nothing hand-derived in between.
    def _autograd_grads(self, O, P, target):
        Ov = O.clone().requires_grad_(True)
        Pv = P.clone().requires_grad_(True)
        psi = _reference_psi(Ov, Pv, self.H_fwd, self.H_rev)
        loss = 0.5 * ((psi - target).abs() ** 2).sum()
        loss.backward()
        return Ov.grad, Pv.grad

    def test_object_gradient_matches_autograd(self):
        O, P, I_dat, self.H_fwd, self.H_rev = _setup()
        grad_g, _, _, _, r_field, _ = self._step(O, P, I_dat, self.H_fwd,
                                                 self.H_rev)
        psi = _reference_psi(O, P, self.H_fwd, self.H_rev)
        gO, _ = self._autograd_grads(O, P, (psi + r_field).detach())

        self.assertGreater(float(grad_g.abs().max()), 0.0,
                           "the object gradient is identically zero")
        np.testing.assert_allclose(grad_g.numpy(), -gO.numpy(),
                                   rtol=1e-9, atol=1e-12)

    def test_probe_gradient_matches_autograd(self):
        O, P, I_dat, self.H_fwd, self.H_rev = _setup()
        _, _, grad_P, _, r_field, _ = self._step(O, P, I_dat, self.H_fwd,
                                                 self.H_rev)
        psi = _reference_psi(O, P, self.H_fwd, self.H_rev)
        _, gP = self._autograd_grads(O, P, (psi + r_field).detach())

        self.assertGreater(float(grad_P.abs().max()), 0.0,
                           "the probe gradient is identically zero")
        np.testing.assert_allclose(grad_P.numpy(), -gP.numpy(),
                                   rtol=1e-9, atol=1e-12)

    def test_probe_gradient_is_skipped_on_request(self):
        O, P, I_dat, H_fwd, H_rev = _setup()
        _, _, grad_P, K_P, _, _ = self._step(O, P, I_dat, H_fwd, H_rev,
                                             probe=False)
        self.assertIsNone(grad_P)
        self.assertIsNone(K_P)

    def test_gradients_vanish_at_the_solution(self):
        """
        Data generated by the model itself are a fixed point: the modulus is
        already right, so there is nothing left to correct.
        """
        O, P, _, H_fwd, H_rev = _setup()
        psi = _reference_psi(O, P, H_fwd, H_rev)
        F = _ff_fw(psi)
        I_dat = (F.real**2 + F.imag**2).sum(dim=1)

        grad_g, _, grad_P, _, r_field, I_mod = self._step(O, P, I_dat, H_fwd,
                                                          H_rev)
        np.testing.assert_allclose(I_mod.numpy(), I_dat.numpy(), rtol=1e-12)
        self.assertLess(float(grad_g.abs().max()), 1e-10)
        self.assertLess(float(grad_P.abs().max()), 1e-10)
        self.assertLess(float(r_field.abs().max()), 1e-10)

    # -- the preconditioners -------------------------------------------------
    def test_K_O_is_the_diagonal_of_the_normal_operator(self):
        """
        K_O[j] must be sum_m |phi_j|^2, which for the affine map O -> psi is
        the exact diagonal of A_j^dag A_j: perturb one pixel of one slice and
        the exit wave picks up exactly that much energy.
        """
        O, P, I_dat, H_fwd, H_rev = _setup(B=1)
        _, K_O, _, _, _, _ = self._step(O, P, I_dat, H_fwd, H_rev)

        phi = torch.fft.ifft2(H_fwd * torch.fft.fft2(P).unsqueeze(0))
        expect = (phi.real**2 + phi.imag**2).sum(dim=2).squeeze(1)
        np.testing.assert_allclose(K_O.numpy(), expect.numpy(), rtol=1e-12)

        # and the energy statement itself, on a few pixels
        N, ny, nx = K_O.shape
        psi0 = _reference_psi(O, P, H_fwd, H_rev)
        for j, py, px in ((0, 3, 5), (N - 1, 11, 2)):
            dO = O.clone()
            dO[j, 0, py, px] += 1.0
            dpsi = _reference_psi(dO, P, H_fwd, H_rev) - psi0
            self.assertAlmostEqual(float((dpsi.abs() ** 2).sum()),
                                   float(K_O[j, py, px]), places=9)

    def test_K_P_counts_the_object(self):
        O, P, I_dat, H_fwd, H_rev = _setup()
        _, _, _, K_P, _, _ = self._step(O, P, I_dat, H_fwd, H_rev)
        expect = (O.real**2 + O.imag**2).sum(dim=(0, 1))
        np.testing.assert_allclose(K_P.numpy(), expect.numpy(), rtol=1e-12)


