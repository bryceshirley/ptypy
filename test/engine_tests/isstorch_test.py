@unittest.skipIf(not HAVE_TORCH, "PyTorch is not installed")
class TorchHelpersTest(unittest.TestCase):

    def test_circular_support_radius(self):
        m = base_torch.circular_support(0.5, (32, 32), torch.float64,
                                           torch.device("cpu"))
        self.assertIsNotNone(m)
        self.assertEqual(float(m[16, 16]), 1.0)          # centre is inside
        self.assertEqual(float(m[0, 0]), 0.0)            # corner is outside
        # radius 0.5 * 32 / 2 = 8 pixels from the centre
        self.assertEqual(float(m[16, 16 + 7]), 1.0)
        self.assertEqual(float(m[16, 16 + 8]), 0.0)

    def test_circular_support_disabled(self):
        """Out-of-range values mean 'no support', not 'erase the probe'."""
        for frac in (None, 0.0, 1.0, 1.5, -0.2):
            self.assertIsNone(
                base_torch.circular_support(frac, (8, 8), torch.float64,
                                               torch.device("cpu")),
                f"probe_support = {frac} should disable the support")

    def test_extract_operator_round_trip(self):
        """A propagator and its inverse, as extracted, undo each other."""
        from ptypy.core import geometry

        g = u.Param(energy=1.0, distance=0.1, psize=2e-8, shape=(32, 32),
                    propagation="nearfield")
        G = geometry.Geo(owner=None, pars=g)
        dev = torch.device("cpu")
        fw = base_torch.to_torch(
            base_torch.extract_operator(G.propagator.fw, (32, 32)),
            torch.complex128, dev)
        bw = base_torch.to_torch(
            base_torch.extract_operator(G.propagator.bw, (32, 32)),
            torch.complex128, dev)

        gen = torch.Generator().manual_seed(3)
        w = _rand_c(gen, 2, 32, 32)
        back = base_torch.apply_torch(bw, base_torch.apply_torch(fw, w))
        # ptypy holds the propagator kernel in single precision, so the round
        # trip is only good to about 1e-7 however it is applied.
        np.testing.assert_allclose(back.numpy(), w.numpy(), rtol=1e-5,
                                   atol=1e-7)


