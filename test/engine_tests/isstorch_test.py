#  helpers for the pure-core tests
# ---------------------------------------------------------------------------
def _ff_fw(x):
    """Unitary far field, so that a norm can be compared on both sides."""
    return torch.fft.fft2(x, norm="ortho")


def _ff_bw(x):
    return torch.fft.ifft2(x, norm="ortho")


def _rand_c(gen, *shape):
    return torch.complex(
        torch.rand(shape, generator=gen, dtype=torch.float64) - 0.5,
        torch.rand(shape, generator=gen, dtype=torch.float64) - 0.5,
    )


def _propagators(gen, N, ny, nx):
    """
    A pair of forward / reverse propagator stacks of the shape the core wants.

    Random unit-modulus phases rather than the physical H: the core must not
    care what the phase is, and a random one catches an index or a conjugate
    that a smooth physical phase would hide. H_0 = 1, as in the model.
    """
    ph = 2 * np.pi * torch.rand((N, 1, 1, ny, nx), generator=gen, dtype=torch.float64)
    H_fwd = torch.exp(1j * ph)
    H_fwd[0] = 1.0
    return H_fwd, H_fwd.conj().contiguous()


def _reference_psi(O, P, H_fwd, H_rev):
    """
    psi = P + sum_j F^-1[ H_{-z_j} F[ g_j phi_j ] ],  phi_j = F^-1[ H_{z_j} F[P] ]

    Written straight from the module docstring, independently of the core.
    """
    N, B = O.shape[0], O.shape[1]
    M = P.shape[0]
    psi = P.unsqueeze(0).expand(B, M, *P.shape[-2:]).clone()
    for j in range(N):
        phi_j = torch.fft.ifft2(H_fwd[j, 0, 0] * torch.fft.fft2(P))  # [M, ny, nx]
        for b in range(B):
            g_jb = O[j, b] - 1.0
            scat = torch.fft.fft2(g_jb.unsqueeze(0) * phi_j)
            psi[b] += torch.fft.ifft2(H_rev[j, 0, 0] * scat)
    return psi


def _setup(N=3, B=2, M=2, ny=16, nx=16, seed=7, weak=0.05):
    gen = torch.Generator().manual_seed(seed)
    O = 1.0 + weak * _rand_c(gen, N, B, ny, nx)
    P = _rand_c(gen, M, ny, nx)
    H_fwd, H_rev = _propagators(gen, N, ny, nx)
    I_dat = torch.rand((B, ny, nx), generator=gen, dtype=torch.float64) + 0.1
    return O, P, I_dat, H_fwd, H_rev


