@unittest.skipIf(not HAVE_TORCH, "PyTorch is not installed")
class FirstBornEngineTest(unittest.TestCase):
    """
    The engine on MoonFlowerScan data, whose object and probe are known.

    Twenty iterations at one slice: the frames are exactly pr * obj[patch] with
    no noise, so at N = 1 the forward model is the one that made them and the
    reconstruction has to be close, not merely plausible.
    """

    def setUp(self):
        self.outpath = tempfile.mkdtemp(suffix="isstorch_test")

    def tearDown(self):
        shutil.rmtree(self.outpath)

    @staticmethod
    def _pars(numiter=20, nslices=1, **kw):
        p = u.Param()
        p.name = "ISSTorch"
        p.numiter = numiter
        p.number_of_slices = nslices
        p.slice_thickness = 1e-6
        p.device = "cpu"
        p.precision = "double"
        p.batch_size = 8
        p.probe_update_start = 2
        p.plot_interval = 0
        p.seed = 3
        p.object_denom = "local"
        p.denom_reg = 0.01
        p.update(kw)
        return p

    def _run(self, **kw):
        pars = self._pars(**kw)
        pars.fslices = f"{self.outpath}/slices.h5"
        return tu.EngineTestRunner(pars, output_path=self.outpath,
                                   output_file="firstborn", autosave=False,
                                   verbose_level="warning")

    @staticmethod
    def _engine(P):
        return list(P.engines.values())[-1]

    @staticmethod
    def _overlap(a, b):
        """|<a, b>| / (|a| |b|), which ignores the global phase and scale."""
        a, b = a.ravel(), b.ravel()
        return float(abs(np.vdot(a, b)) / (np.linalg.norm(a) * np.linalg.norm(b)))

    @staticmethod
    def _deramp(d, mask, pad=8):
        """
        The conjugate of the best-fit global phase ramp of ``d`` over ``mask``.

        A linear phase ramp on the object (matched by the opposite ramp on the
        probe) leaves every diffraction pattern unchanged, so no engine can fix
        it and comparing to the truth without removing it is meaningless: it
        costs the stock DM engine 0.94 -> 0.49 on the metric below. The ramp is
        found from the peak of the zero-padded FFT, which leaves a residual
        small enough to finish with a plain least-squares fit -- no unwrapping.
        """
        ny, nx = d.shape
        yy, xx = np.mgrid[:ny, :nx]
        D = np.fft.fft2(np.where(mask, d, 0), s=(pad * ny, pad * nx))
        ky, kx = np.unravel_index(np.argmax(np.abs(D)), D.shape)
        ky -= pad * ny * (ky > pad * ny // 2)
        kx -= pad * nx * (kx > pad * nx // 2)
        coarse = np.exp(-2j * np.pi * (ky * yy / (pad * ny) + kx * xx / (pad * nx)))
        A = np.stack([np.ones(mask.sum()), yy[mask], xx[mask]], 1)
        c = np.linalg.lstsq(A, np.angle((d * coarse)[mask]), rcond=None)[0]
        return coarse * np.exp(-1j * (c[0] + c[1] * yy + c[2] * xx))

    def _object_fidelity(self, P):
        """
        Overlap of the reconstructed object with the one the data came from.

        Only the well-illuminated pixels count: the rim of the storage is seen
        by a couple of views at the very edge of the probe, is not constrained
        by them, and runs away to amplitudes of order 100, which on its own
        drags the overlap of a perfectly good reconstruction below 0.1.
        """
        st = list(P.obj.storages.values())[0]
        rec = st.data[0]
        cvg = st.get_view_coverage()[0]
        mask = cvg > 0.5 * cvg.max()
        # MoonFlowerScan cuts its frames at obj[pixel:pixel + shape] and ptypy
        # lays the storage out on the same grid, offset by the 10 pixel margin
        # the scan adds; verified frame by frame from pod.ob_view.dlow.
        truth = P.model.scans["MF"].ptyscan.obj[10:10 + rec.shape[0],
                                                10:10 + rec.shape[1]]
        rec = rec * self._deramp(rec * np.conj(truth), mask)
        return self._overlap(rec[mask], truth[mask])

    def test_error_decreases(self):
        P = self._run()
        err = np.array([v["error"][0] for v in P.runtime.iter_info])
        self.assertLess(err[-1], err[0],
                        "the Fourier error did not fall over 20 iterations")
        self.assertLess(err[-1], 0.5 * err[0],
                        "the Fourier error barely moved")

    def test_object_is_actually_updated(self):
        """
        Every illuminated pixel must have moved off the flat start, and the
        untouched ones must not have. A blank update passes an error check that
        only looks at the probe, so it is asserted here directly.
        """
        P = self._run()
        eng = self._engine(P)
        ob = eng.ob_g[0].cpu().numpy()
        cov = eng.cov.cpu().numpy()

        moved = np.abs(ob - 1.0)
        self.assertGreater(moved[cov].mean(), 1e-3,
                           "the illuminated object did not move off 1")
        # the start is 1 + 1e-3 noise, so anything never illuminated stays there
        self.assertLess(moved[~cov].max(), 2e-3,
                        "pixels no view touches were modified")

    def test_recovers_the_moonflower_object(self):
        """
        Thresholds are calibrated against the stock engines on this same data:
        at 20 iterations ISSTorch scores 0.90, DM 0.94 and EPIE 0.73.
        """
        self.assertGreater(
            self._object_fidelity(self._run()), 0.8,
            "the reconstruction does not match the object the data came from")

    def test_probe_is_recovered(self):
        """0.80 here, against 0.77 for DM and 0.78 for EPIE at 20 iterations."""
        P = self._run()
        eng = self._engine(P)
        truth = P.model.scans["MF"].ptyscan.pr
        rec = eng.pr_g[0].cpu().numpy()
        self.assertGreater(self._overlap(rec, truth), 0.7,
                           "the probe does not match the illumination used")

    def test_probe_support_is_applied(self):
        """
        probe_support follows BaseEngine's convention: setting the
        fraction applies the circular support.
        """
        P = self._run(probe_support=0.3)
        eng = self._engine(P)
        self.assertIsNotNone(eng.pr_support)
        outside = eng.pr_support.cpu().numpy() == 0
        self.assertEqual(
            float(np.abs(eng.pr_g[0].cpu().numpy()[outside]).max()), 0.0,
            "the probe is not zero outside its support")

    def test_no_support_when_probe_support_is_none(self):
        P = self._run(probe_support=None)
        self.assertIsNone(self._engine(P).pr_support)

    def test_two_slices_run_and_multiply_to_the_object(self):
        """
        The saved ptypy object is the product of the slices; with two slices
        that has to hold exactly at the end of the run.
        """
        P = self._run(nslices=2)
        eng = self._engine(P)
        prod = (eng.ob_g[0] * eng.ob_g[1]).cpu().numpy()
        np.testing.assert_allclose(
            list(P.obj.storages.values())[0].data[0], prod, rtol=1e-6,
            atol=1e-8)

    def test_gather_and_scatter_are_adjoint(self):
        """
        <scatter(v), w> == <v, gather(w)>: the object patches go back exactly
        where they were taken from. A transposed index here is invisible in the
        error metric but puts every update in the wrong place.
        """
        P = self._run(numiter=1)
        eng = self._engine(P)
        gen = torch.Generator().manual_seed(11)
        idx = torch.arange(4)
        flat = eng._flat(idx)

        v = torch.rand((4, eng.fny, eng.fnx), generator=gen,
                       dtype=eng.rdt).to(eng.dev)
        w = torch.rand((eng.ony, eng.onx), generator=gen,
                       dtype=eng.rdt).to(eng.dev)
        dst = torch.zeros_like(w)
        eng._scatter(dst, flat, v)

        lhs = float((dst * w).sum())
        rhs = float((v * eng._gather(w, flat, 4)).sum())
        self.assertAlmostEqual(lhs, rhs, places=8)

    def test_two_engines_in_one_run_do_not_collide(self):
        """
        A probe warm-up followed by a multislice stage asks for the same
        container names twice; ptypy answers a duplicate with an
        UnboundLocalError, so the names have to be made unique.
        """
        # tu.EngineTestRunner puts its argument at p.engines.engine00, so it
        # cannot express a two-stage run; this is the same setup by hand.
        p = u.Param()
        p.frames_per_block = 100000
        p.verbose_level = "warning"
        p.io = u.Param()
        p.io.home = self.outpath
        p.io.rfile = "chained.ptyr"
        p.io.interaction = u.Param(active=False)
        p.io.autosave = u.Param(active=False)
        p.io.autoplot = u.Param(active=False)
        p.scans = u.Param()
        p.scans.MF = u.Param()
        p.scans.MF.name = "Full"
        p.scans.MF.propagation = "farfield"
        p.scans.MF.data = u.Param(name="MoonFlowerScan", num_frames=200,
                                  shape=64, save=None, photons=1e8, psf=0.0,
                                  density=0.2, add_poisson_noise=False)
        p.scans.MF.coherence = u.Param(num_probe_modes=1)
